/** Intel 8085A, 40-pin DIP. Pin 1 is the notch end of the left row. */

export type PinSide = "L" | "R";
export type PinDir = "in" | "out" | "both" | "power";

export type Pin8085 = {
  id: string;
  /** Printed name. CLK is "CLK (OUT)" on the package diagram. */
  name: string;
  n: number;
  side: PinSide;
  /** 0 is the notch end of that row. */
  index: number;
  dir: PinDir;
  /** One line for the observation table. */
  role: string;
};

