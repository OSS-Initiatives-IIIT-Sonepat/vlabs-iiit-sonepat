export const PIN_IDS_8085 = PINS_8085.map((pin) => pin.id);

const byId = new Map(PINS_8085.map((pin) => [pin.id, pin]));

export function pin8085(id: string): Pin8085 {
  const pin = byId.get(id);
  if (!pin) throw new Error(`Unknown 8085 pin ${id}`);
  return pin;
}
